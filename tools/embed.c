/**
 * @file embed.c
 * @brief Tool build untuk mengonversi file biner atau teks menjadi source C.
 *
 * Penggunaan: embed <file_input> <nama_simbol> <file_output.c>
 *
 * Output berisi dua simbol global:
 *   const unsigned char <nama_simbol>[]      isi file ditambah satu byte nol di akhir
 *   const unsigned long <nama_simbol>_size   ukuran isi file tanpa byte nol penutup
 *
 * Byte nol penutup membuat data teks dapat langsung dipakai sebagai string C.
 */

#include <stdio.h>
#include <stdlib.h>

int main(int argc, char **argv)
{
    FILE *in;
    FILE *out;
    unsigned long size = 0;
    int ch;

    /* Argument Validation */
    if (argc != 4) {
        fprintf(stderr, "usage: embed <input> <symbol> <output.c>\n");
        return 1;
    }

    /* File Opening */
    in = fopen(argv[1], "rb");
    if (in == NULL) {
        fprintf(stderr, "embed: cannot open input '%s'\n", argv[1]);
        return 1;
    }
    out = fopen(argv[3], "wb");
    if (out == NULL) {
        fprintf(stderr, "embed: cannot open output '%s'\n", argv[3]);
        fclose(in);
        return 1;
    }

    /* Array Emission */
    fprintf(out, "/* Generated by tools/embed.c from %s. Do not edit. */\n\n", argv[1]);
    fprintf(out, "const unsigned char %s[] = {\n", argv[2]);
    while ((ch = fgetc(in)) != EOF) {
        fprintf(out, "%s0x%02x,", (size % 16 == 0) ? "\n    " : " ", (unsigned)ch);
        size++;
    }
    fprintf(out, "%s0x00\n};\n\n", (size % 16 == 0) ? "\n    " : " ");
    fprintf(out, "const unsigned long %s_size = %luUL;\n", argv[2], size);

    /* Cleanup */
    fclose(in);
    if (fclose(out) != 0) {
        fprintf(stderr, "embed: failed writing '%s'\n", argv[3]);
        return 1;
    }
    return 0;
}
